import assert from 'node:assert/strict';
import { createTrainer, createLead, getLeadById, getLeads, updateLead, getLeadAssignments, deleteLead } from '../src/services/dataService';
import { parseSessionNumber } from '../src/utils/sessionNumber';

const centerId = 'synthetic-ot-center';
const trainer = (name: string, center = centerId, status: 'ACTIVE' | 'INACTIVE' = 'ACTIVE') => createTrainer({ centerId: center, name, phone: '01012345678', specialty: '운동', role: 'TRAINER', status });
const a = await trainer('트레이너 A');
const b = await trainer('트레이너 B');
const outside = await trainer('다른 센터', 'synthetic-other');
const inactive = await trainer('퇴사', centerId, 'INACTIVE');
const data = { centerId, name: '가상 문의자', phone: '01012345678', inquiryDate: '2026-11-23', source: '방문' as const, status: 'NEW' as const };
const lead = await createLead(data, 'TRAINER', a.trainerId);
assert.equal(lead.assignedTrainerId, a.trainerId, 'defaults to registering trainer');
const second = await createLead({ ...data, assignedTrainerId: b.trainerId }, 'TRAINER', a.trainerId);
assert.equal(second.assignedTrainerId, b.trainerId, 'can assign a different trainer');
assert.equal((await getLeads(centerId, 'TRAINER', b.trainerId)).length, 2, 'staff can find unassigned and other staff leads');
await assert.rejects(createLead(data, 'MEMBER'));
await assert.rejects(createLead(data, 'TRAINER', null));
await assert.rejects(createLead({ ...data, assignedTrainerId: outside.trainerId }, 'TRAINER', a.trainerId));
await assert.rejects(createLead({ ...data, assignedTrainerId: inactive.trainerId }, 'TRAINER', a.trainerId));
await assert.rejects(updateLead(centerId, lead.leadId, { status: 'OT_COMPLETED' }, 'TRAINER', b.trainerId));
await assert.rejects(updateLead(centerId, lead.leadId, { memo: '다른 담당 기록 수정' }, 'TRAINER', b.trainerId));
const assigned = await updateLead(centerId, lead.leadId, { assignedTrainerId: b.trainerId, status: 'OT_SCHEDULED', otDate: '2026-11-24' }, 'TRAINER', b.trainerId);
assert.equal(assigned.assignmentVersion, 2);
assert.equal(assigned.assignedTrainerName, b.name);
await assert.rejects(updateLead(centerId, lead.leadId, { status: 'OT_COMPLETED' }, 'TRAINER', a.trainerId));
await updateLead(centerId, lead.leadId, { status: 'OT_COMPLETED', memo: '담당자 완료' }, 'TRAINER', b.trainerId);
assert.equal((await getLeadById(centerId, lead.leadId, 'TRAINER', b.trainerId))?.status, 'OT_COMPLETED');
const history = await getLeadAssignments(centerId, lead.leadId);
assert.equal(history.length, 2, 'record editing does not invent assignment changes');
assert.equal(history[0].previousTrainerId, a.trainerId);
assert.equal(history[0].assignedTrainerId, b.trainerId);
assert.ok(history[0].changedByUid && history[0].changedAt);
await assert.rejects(updateLead('synthetic-other', lead.leadId, { assignedTrainerId: outside.trainerId }, 'TRAINER', outside.trainerId));
await assert.rejects(deleteLead(centerId, lead.leadId, 'TRAINER'));
await deleteLead(centerId, second.leadId, 'CENTER_ADMIN');
for (const value of ['', '0', '-1', '1.5', '1e2', 'abc', '9007199254740992']) assert.equal(parseSessionNumber(value), null);
assert.equal(parseSessionNumber('35'), 35);
assert.equal(parseSessionNumber('1'), 1);
console.log('OT staff workflow and session number checks passed (synthetic data, no production access).');
